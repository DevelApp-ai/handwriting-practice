export interface StrokePoint {
  x: number
  y: number
}

export interface Stroke {
  points: StrokePoint[]
  order: number
}

export interface StrokeOrderData {
  character: string
  strokes: Stroke[]
}

/**
 * Generate stroke order data for a character
 * Supports Latin letters (A-Z, a-z), numbers (0-9), punctuation,
 * Arabic letters, Japanese Hiragana/Katakana, and Nepali Devanagari
 */
export function generateBasicStrokeOrder(character: string): StrokeOrderData {
  const strokes: Stroke[] = []
  
  if (character.length === 1) {
    const basicStrokes = getBasicLetterStrokes(character)
    basicStrokes.forEach((points, index) => {
      strokes.push({
        points,
        order: index + 1
      })
    })
  } else if (character.length > 1) {
    // For words/sentences, return empty - stroke order not applicable
    return { character, strokes: [] }
  }
  
  return {
    character,
    strokes
  }
}

/**
 * Get stroke data for a single character
 */
function getBasicLetterStrokes(char: string): StrokePoint[][] {
  const normalized = char.toUpperCase()
  const lowerChar = char.toLowerCase()
  
  // Check Arabic characters first
  const arabicStrokes = getArabicStroke(char)
  if (arabicStrokes) return arabicStrokes
  
  // Check Japanese characters
  const japaneseStrokes = getJapaneseStroke(char)
  if (japaneseStrokes) return japaneseStrokes
  
  // Check Nepali/Devanagari characters
  const nepaliStrokes = getNepaliStroke(char)
  if (nepaliStrokes) return nepaliStrokes
  
  // Latin characters
  const latinStrokes = getLatinStrokeData(normalized) || getLatinStrokeData(lowerChar)
  if (latinStrokes) return latinStrokes
  
  // Numbers
  const numberStrokes = getNumberStrokeData(char)
  if (numberStrokes) return numberStrokes
  
  // Punctuation
  const punctuationStrokes = getPunctuationStrokeData(char)
  if (punctuationStrokes) return punctuationStrokes
  
  // Default: simple box stroke
  return [
    [{x: 0.3, y: 0.3}, {x: 0.7, y: 0.3}, {x: 0.7, y: 0.7}, {x: 0.3, y: 0.7}, {x: 0.3, y: 0.3}]
  ]
}

